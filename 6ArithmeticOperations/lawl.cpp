#include <iostream>

int main()
{
    int a = 20;
    int b = 6;

    // calculate and print:
    std::cout << "Addition of the given numbers is: " << a+b <<"\n";
    std::cout << "Substraction of the given numbers is: " << a-b <<"\n";
    std::cout << "Multiplication of the given numbers is: " << a*b <<"\n";
    std::cout << "Division of the given numbers is: " << a/b <<"\n";
    std::cout << "Reminder of the given numbers is: " << a%b <<"\n";
}