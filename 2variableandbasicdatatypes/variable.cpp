#include <iostream>

int main() {

    int x; // declaration that there is a variable named x of type int(integer)
    int y; //declaration that there is a vaariable called y of type int

    x = 5;  //asignment that gives x the value of 5
    y = 6; //asignment that gives y the value of 6
    int sum = x + y;

    std::cout << x << '\n';
    std::cout << y << '\n';
    std::cout << sum << '\n';
    return 0;
}

